// 用例：读写门（模块内「读并发 / 写独占」）
//   同一批任务（256 个、每个约 40 µs 业务）分别以「读」「写」过门：
//     PostRead —— 读任务可并发进入（上限 = 执行器线程数）
//     Post     —— 默认写任务独占（同一执行器内串行）
//   基线 = 同一批工作直接顺序执行（无调度）。
//   实测（4 线程 / 2000 任务）：写 45.4 ms、读 10.8 ms ≈ **4.2×**（≈ 线程数）。
//
//   注意任务规模：线程池在「队列空窗」下每任务有 ~5~15 µs 的睡眠/唤醒成本，
//   任务只有几百纳秒时测到的是调度而不是读写门（读、写都会退化到「一次唤醒跑一个任务」）。
//   要看短任务的表现请配合 `5. 压力测试`（窗口式持续吞吐）。
