// ====================================================================
// 单独的例子：一条 promise 链里混用多种 then
//
// 目的：把「then 到底用哪种写法」放在**同一条下单流程**里对照，一眼看清取舍：
//
//   ① then = 具名异步函数            读订单（有名字、可复用、可单测；内部模拟 IO）
//   ② then = lambda                  就地校验（只此一处用的小逻辑，不进具名函数）
//   ③ then = 内部执行「其他异步函数」 查库存（**要等它**：ThenPromise + exec.NewPromise(spCtx, fnStarter) 桥接）
//   ④ then = 具名异步函数            算折扣
//   ④+ then = lambda 里现搭的内层 then 链（同上下文，直接 adopt 进当前链）
//   ⑤ then = 内部执行「其他异步函数」 记账旁支（**不等它**：fire-and-forget，主链继续）
//   ⑥ then = 具名异步函数            落库
//   catch = 具名异步函数             补偿（仅被拒绝时执行）
//   finally = 具名异步函数           审计（无论成败都执行、不改结果）
//
// 全流程零阻塞、不用协程：只有本用例末尾（主线程断言）才用 Await 取最终结果。
//
// 模块边界：库存 / 记账在 .cpp 里都是「自持执行器」的小模块（执行器不跨模块传递），
//          调用方只拿对方的 promise 并用桥接等待 —— 顺序由「依赖边」保证，不靠共享线程。
// 实现见 ThenMixCase.cpp。
// ====================================================================

