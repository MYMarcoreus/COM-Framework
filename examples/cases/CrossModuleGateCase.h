// ====================================================================
// 例子：跨模块起链时，被调模块的状态由**哪扇门**保护
//
// 两个模块各有自己的执行器（= 自己的读写门），状态是普通成员（安全来自读写门）：
//   CCalleeModule  被调模块：对外只有 QueryAsync()（**起链回调里碰自己的状态**）
//   CCallerModule  调用方模块：链只用 then 系列组装（跨模块那一步在 ThenPromise 的工厂里）
//
// 对照点（D 之前 / 之后的差别）：
//   之前：起链回调在**调用方的线程**上同步跑、继承**调用方的门** —— 对 B 而言是门外，
//         碰 B 的状态就与 B 自己的写任务并发（TSan 报 data race）；
//   现在：门外 / 别的门 / 换类别起链一律**按声明类别过门投递**后再跑 ——
//         起链回调落在**自己被调模块的门**里（同类槽位则就地，零开销）。
//
// 用例同时跑「B 自己的写链」与「A 的跨模块链」，用重叠计数器自校验：
// 被调模块的状态段任意时刻只有一个进入者（重叠次数必须为 0），且计数精确。
//
// 实现见 CrossModuleGateCase.cpp。
// ====================================================================

/// @brief 运行「跨模块起链」用例（自校验：状态计数精确、状态段无重叠进入）。
///
/// @return true 全部自校验通过；false 有断言失败。
bool RunCrossModuleGateCase();
